/// SQXTN2B (Signed Saturating Extract Narrow 2 Bottom) semantics are representable in the IR.
/// Stanford source: arm64_md_clean/sqxtn2b.md
/// Signed saturating extract narrow 2 bottom. Requires FEAT_SVE.
use semantic_ir::{
    BitWidth, Expr, Instruction, InstructionId, Provenance, Stmt, Width,
    validate_instruction,
};

fn sqxtn2b_instruction(mnemonic: &str) -> Instruction {
    let data = Expr::ReadScalableVecReg {
        reg: 0,
        vl: BitWidth::W128,
    };

    let semantics = vec![Stmt::WriteScalableVecReg {
        reg: 0,
        value: data,
        vl: BitWidth::W128,
    }];

    Instruction {
        id: InstructionId {
            mnemonic: mnemonic.to_string(),
            encoding: Some("Signed Saturating Extract Narrow 2 Bottom".to_string()),
        },
        operands: Vec::new(),
        required_features: vec!["FEAT_SVE".to_string()],
        decode: None,
        semantics,
        provenance: Provenance {
            source_path: "sqxtn2b.md".to_string(),
            source_sha256: "test-source-sha256".to_string(),
            clean_sha256: "test-clean-sha256".to_string(),
        },
    }
}

#[test]
fn sqxtn2b_validates() {
    validate_instruction(&sqxtn2b_instruction("SQXTN2B"))
        .expect("SQXTN2B should validate");
}
