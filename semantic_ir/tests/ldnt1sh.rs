/// LDNT1SH (Load Non-temporal 1 Signed Halfword) semantics are representable in the IR.
/// Stanford source: arm64_md_clean/ldnt1sh.md
/// Load Non-temporal 1 Signed Halfword. Requires FEAT_SVE.
use semantic_ir::{
    BitWidth, Expr, Instruction, InstructionId, Provenance, Stmt, Width,
    validate_instruction,
};

fn ldnt1sh_instruction(mnemonic: &str) -> Instruction {
    let data = Expr::ReadScalableVecReg {
        reg: 0,
        vl: BitWidth::W128,
    };

    let semantics = vec![Stmt::WriteScalableVecReg {
        reg: 0,
        value: data,
        vl: BitWidth::W128,
    }];

    Instruction {
        id: InstructionId {
            mnemonic: mnemonic.to_string(),
            encoding: Some("Load Non-temporal 1 Signed Halfword".to_string()),
        },
        operands: Vec::new(),
        required_features: vec!["FEAT_SVE".to_string()],
        decode: None,
        semantics,
        provenance: Provenance {
            source_path: "ldnt1sh.md".to_string(),
            source_sha256: "test-source-sha256".to_string(),
            clean_sha256: "test-clean-sha256".to_string(),
        },
    }
}

#[test]
fn ldnt1sh_validates() {
    validate_instruction(&ldnt1sh_instruction("LDNT1SH"))
        .expect("LDNT1SH should validate");
}
