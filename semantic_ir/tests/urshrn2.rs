/// URSHRN2 (Unsigned Rounding Shift Right Narrow 2) semantics are representable in the IR.
/// Stanford source: arm64_md_clean/urshrn2.md
/// Unsigned rounding shift right narrow 2. Requires FEAT_SVE.
use semantic_ir::{
    BitWidth, Expr, Instruction, InstructionId, Provenance, Stmt, Width,
    validate_instruction,
};

fn urshrn2_instruction(mnemonic: &str) -> Instruction {
    let data = Expr::ReadScalableVecReg {
        reg: 0,
        vl: BitWidth::W128,
    };

    let semantics = vec![Stmt::WriteScalableVecReg {
        reg: 0,
        value: data,
        vl: BitWidth::W128,
    }];

    Instruction {
        id: InstructionId {
            mnemonic: mnemonic.to_string(),
            encoding: Some("Unsigned Rounding Shift Right Narrow 2".to_string()),
        },
        operands: Vec::new(),
        required_features: vec!["FEAT_SVE".to_string()],
        decode: None,
        semantics,
        provenance: Provenance {
            source_path: "urshrn2.md".to_string(),
            source_sha256: "test-source-sha256".to_string(),
            clean_sha256: "test-clean-sha256".to_string(),
        },
    }
}

#[test]
fn urshrn2_validates() {
    validate_instruction(&urshrn2_instruction("URSHRN2"))
        .expect("URSHRN2 should validate");
}
